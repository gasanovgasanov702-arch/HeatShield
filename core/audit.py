# Этот модуль отдельно перепроверяет точки-кандидаты относительно объектов OpenStreetMap.
"""Independent checks of recommendations against the downloaded OSM geometry."""

# Включаем современные правила аннотаций типов, не меняя работу программы во время запуска.
from __future__ import annotations

# Point создаёт геометрическую точку из координат кандидата в метрах.
from shapely.geometry import Point
# unary_union объединяет множество геометрий препятствий в одну для удобного измерения расстояния.
from shapely.ops import unary_union

# Candidate описывает возможное место посадки и содержит его координаты и номер.
from core.free_space import Candidate
# Placement хранит номера выбранных мест; здесь он нужен для чтения списка ids.
from core.optimizer import Placement


# Для каждого типа объекта задаём минимальное расстояние до дерева в метрах.
_CLEARANCES={"buildings":5.0,"roads":5.0,"footways":2.0,"sidewalks":8.0,"green":0.0,
             # У зелени нет обязательного отступа, а от воды, деревьев и точек притяжения есть заданные отступы.
             "water":5.0,"trees":5.0,"restricted":5.0,"attractors":2.0}


# Проверяем выбранные точки и возвращаем счётчики, нарушения и предупреждения.
def audit_selection(candidates:list[Candidate],placement:Placement,layers:dict)->dict:
    # По номеру кандидата быстро находим его объект с координатами и данными.
    lookup={candidate.id:candidate for candidate in candidates}
    # Сюда будем добавлять описания обнаруженных проблем.
    violations=[]
    # Счётчик реально найденных и проверенных выбранных кандидатов.
    checked=0
    # Собираем геометрии валидных объектов каждого типа в единую геометрию-препятствие.
    obstacles={name:unary_union([g for g in layers[name].geometry if g is not None and not g.is_empty and g.is_valid])
               # Перебираем все типы слоёв, для которых выше определены отступы.
               for name in _CLEARANCES if name in layers}
    # Проходим по номерам точек, которые входят в предлагаемое размещение.
    for candidate_id in placement.ids:
        # Ищем полный объект кандидата по его номеру.
        candidate=lookup.get(candidate_id)
        # Если номера нет среди кандидатов, отметить это и перейти к следующему номеру.
        if candidate is None:
            # Выбранный номер должен принадлежать текущему списку кандидатов.
            violations.append(f"Неизвестный кандидат #{candidate_id}")
            # Нельзя измерить отступ, если координаты номера неизвестны.
            continue
        # Увеличиваем число проверенных известных кандидатов.
        checked+=1
        # Создаём геометрическую точку по координатам x и y; в проектированной системе это метры.
        point=Point(candidate.x,candidate.y)
        # Сравниваем эту точку с каждым видом препятствий и нужным отступом.
        for name,clearance in _CLEARANCES.items():
            # Отсутствующий в старых сценариях слой не создаёт препятствия.
            if name not in obstacles:continue
            # Берём объединённую геометрию объектов текущего слоя.
            obstacle=obstacles[name]
            # Пустой слой ничего не ограничивает, поэтому расстояние для него считать не нужно.
            if obstacle.is_empty:continue
            # Shapely возвращает кратчайшее расстояние между точкой и объектом; здесь единица — метр.
            distance=point.distance(obstacle)
            # Допуск 0.1 м смягчает погрешность геометрии; зелень с нулевым отступом проверяем на попадание внутрь.
            if distance+0.1<clearance or (clearance==0 and obstacle.contains(point)):
                # Записываем номер точки, вид слоя, измеренное расстояние и требуемое расстояние в метрах.
                violations.append(f"Точка #{candidate_id}: {name}, расстояние {distance:.1f} м < {clearance:.1f} м")
    # Формируем отдельный список неполноты исходных данных: это предупреждения, а не геометрические нарушения.
    warnings=[]
    # Если нет ни парков/зелёных зон, ни отдельных деревьев, модель не может оценить их дефицит по карте.
    if len(layers["green"])+len(layers["trees"])==0:
        # Сообщаем, что оценка зелени не опирается на нанесённые объекты карты.
        warnings.append("В OSM нет размеченной зелени на участке: дефицит оценён нейтрально.")
    # Отсутствие размеченных мест притяжения означает, что модель спроса пешеходов не получила исходных точек.
    if len(layers["attractors"])==0:
        # Без точек притяжения пешеходный показатель основан не на данных OSM.
        warnings.append("Нет размеченных точек притяжения: пешеходный спрос по модели не оценён.")
    # Если дорожки не выделены на карте отдельным тегом, советуем проверить их на местности.
    if len(layers["footways"])==0:
        # Предупреждаем о возможной неполноте пешеходной карты района.
        warnings.append("Нет отдельно размеченных пешеходных дорожек; используйте полевой осмотр.")
    # Возвращаем число проверок, проблемы и предупреждения, а также число объектов в каждом слое OSM.
    return {"checked":checked,"violations":violations,"warnings":warnings,
            # Для каждого слоя считаем строки GeoDataFrame, то есть число загруженных объектов этого типа.
            "osm_objects":{name:len(frame) for name,frame in layers.items()}}
