# Модуль безопасно извлекает широту и долготу из ссылок Google Maps.
"""Parse coordinates from Google Maps links without fetching arbitrary URLs."""

# Откладываем обработку аннотаций типов, сохраняя обычное поведение Python.
from __future__ import annotations

# math нужен, чтобы отбрасывать бесконечные и неопределённые числовые координаты.
import math
# re позволяет находить числовые пары и форматы координат внутри текста ссылки.
import re
# parse_qs разбирает параметры после ?, а urlparse отделяет домен, путь и параметры URL.
from urllib.parse import parse_qs, urlparse
# urljoin превращает относительный адрес перенаправления в полный адрес.
from urllib.parse import urljoin
# Эти классы создают HTTP-клиент, который можно настроить на запрет автоматических переходов.
from urllib.request import HTTPRedirectHandler, Request, build_opener
# HTTPError содержит код ответа и заголовки, в том числе адрес Location перенаправления.
from urllib.error import HTTPError


# Шаблон ищет пару чисел широта,долгота, например 51.5,-0.1, в параметре ссылки.
_PAIR = re.compile(r"(?P<lat>[+-]?\d{1,2}(?:\.\d+)?),(?P<lon>[+-]?\d{1,3}(?:\.\d+)?)")
# Google часто записывает центр карты в пути после символа @.
_AT = re.compile(r"@(?P<lat>[+-]?\d{1,2}(?:\.\d+)?),(?P<lon>[+-]?\d{1,3}(?:\.\d+)?)")
# В длинных ссылках Google координаты иногда имеют вид !3dширота!4dдолгота.
_BANG = re.compile(r"!3d(?P<lat>[+-]?\d+(?:\.\d+)?)!4d(?P<lon>[+-]?\d+(?:\.\d+)?)")
# Разрешаем только точные известные домены Google, чтобы не запрашивать адреса посторонних сайтов.
_ALLOWED_HOSTS = {"google.com", "www.google.com", "maps.google.com", "maps.app.goo.gl", "goo.gl"}


# Этот обработчик перехватывает ответы с перенаправлением и возвращает их вызывающему коду.
class _NoRedirect(HTTPRedirectHandler):
    # HTTP 301 означает постоянное перенаправление; вместо перехода сохраняем ответ для проверки.
    def http_error_301(self, req, fp, code, msg, headers):
        # Возвращаем ответ вызывающему коду, чтобы проверить адрес перенаправления вручную.
        raise HTTPError(req.full_url, code, msg, headers, fp)
    # Остальные типы перенаправления используют ту же защитную логику.
    http_error_302 = http_error_301
    # Временное перенаправление 303 также не должно обходить проверку адреса.
    http_error_303 = http_error_301
    # Временное перенаправление 307 сохраняет метод запроса и тоже требует ручной проверки.
    http_error_307 = http_error_301
    # Перенаправление 308 постоянное и обрабатывается тем же способом.
    http_error_308 = http_error_301


# Проверяем мировые диапазоны координат и возвращаем исходную пару чисел.
def validate_coordinates(lat: float, lon: float) -> tuple[float, float]:
    # Широта должна быть конечным числом от -90 до 90 градусов, долгота — от -180 до 180.
    if not all(math.isfinite(v) for v in (lat, lon)) or not (-90 <= lat <= 90 and -180 <= lon <= 180):
        # Некорректная пара вызывает понятную ошибку вместо передачи неверной точки дальше.
        raise ValueError("Координаты вне допустимого диапазона.")
    # Возвращаем широту и долготу в том же порядке, в каком их ожидают функции проекта.
    return lat, lon


# Извлекаем координаты из полной ссылки Maps, не выполняя сетевой запрос.
def parse_google_maps_url(url: str) -> tuple[float, float]:
    # Убираем пробелы по краям и разбираем URL на составляющие.
    parsed = urlparse(url.strip())
    # Разрешены только HTTP/HTTPS ссылки с доменом из белого списка.
    if parsed.scheme not in {"https", "http"} or parsed.hostname not in _ALLOWED_HOSTS:
        # Протокол и точный домен должны совпасть с разрешённым списком Google Maps.
        raise ValueError("Нужна ссылка на Google Maps с допустимым доменом.")
    # Запрещаем имя пользователя, пароль и нестандартный порт в URL.
    if parsed.username or parsed.password or parsed.port:
        # Имя пользователя, пароль и порт не ожидаются в обычной ссылке Maps.
        raise ValueError("Недопустимый формат ссылки.")
    # Сначала ищем распространённые форматы координат прямо в пути и параметрах URL.
    for pattern in (_AT, _BANG):
        # Соединяем путь с параметрами, чтобы шаблон мог найти координаты в любой части.
        match = pattern.search(parsed.path + "?" + parsed.query)
        # Если формат найден, переводим обе захваченные группы из текста в числа и проверяем диапазон.
        if match:
            # Переводим захваченную широту и долготу в числа градусов и проверяем диапазон.
            return validate_coordinates(float(match["lat"]), float(match["lon"]))
    # Преобразуем query-параметры URL в словарь: ключу соответствует список значений.
    query = parse_qs(parsed.query)
    # Google использует несколько названий параметров для координат или поискового запроса.
    for key in ("q", "query", "ll", "center"):
        # У одного ключа может быть несколько значений, поэтому проверяем каждое.
        for value in query.get(key, []):
            # В значении параметра ищем пару чисел широта,долгота.
            match = _PAIR.search(value)
            # Найденные текстовые числа валидируем и возвращаем как числовую пару.
            if match:
                # Возвращаем первую координатную пару параметров после проверки диапазона.
                return validate_coordinates(float(match["lat"]), float(match["lon"]))
    # Короткая ссылка обычно содержит идентификатор, но не сами координаты.
    if parsed.hostname in {"maps.app.goo.gl", "goo.gl"}:
        # Короткая ссылка требует раскрытия, потому что её текст обычно не содержит координат.
        raise ValueError("Короткая ссылка не содержит координат. Откройте её в браузере и скопируйте полную ссылку.")
    # Если ни один известный формат не подошёл, сообщаем, что координаты можно ввести вручную.
    raise ValueError("Координаты не найдены в ссылке. Можно ввести широту и долготу вручную.")


# Раскрываем короткую ссылку с ограничением на домен и максимум четыре перехода.
def resolve_short_google_url(url: str) -> tuple[float, float]:
    # Эта строка фиксирует безопасные условия раскрытия короткой ссылки.
    """Follow only HTTPS redirects among exact Google-owned hosts, at most four hops."""
    # Начинаем с адреса без случайных пробелов.
    current = url.strip()
    # Создаём HTTP-клиент, который отдаёт перенаправления коду для проверки.
    opener = build_opener(_NoRedirect())
    # Ограничиваем число переходов, чтобы не зациклиться на цепочке коротких ссылок.
    for _ in range(4):
        # Перед каждым запросом заново разбираем текущий адрес.
        parsed = urlparse(current)
        # Разрешаем только HTTPS, известный домен и обычный URL без учётных данных и порта.
        if parsed.scheme != "https" or parsed.hostname not in _ALLOWED_HOSTS or parsed.username or parsed.password or parsed.port:
            # Не продолжаем переход, если текущий URL вышел за пределы HTTPS-доменов Google.
            raise ValueError("Короткая ссылка перенаправляет на недопустимый адрес.")
        # Сначала пробуем извлечь координаты без сети: ссылка может уже быть полной.
        try:
            # Проверяем, можно ли прочитать координаты без сетевого запроса.
            return parse_google_maps_url(current)
        # Отсутствие координат ожидаемо для короткой ссылки, поэтому тогда запрашиваем её заголовки.
        except ValueError:
            # Для короткой ссылки отсутствие координат ожидаемо; далее запросим заголовки.
            pass
        # HEAD просит сервер ответить заголовками без загрузки тела страницы.
        request = Request(current, method="HEAD", headers={"User-Agent": "HeatShield/1.0"})
        # Отправляем запрос с тайм-аутом 10 секунд, чтобы ожидание сети было ограничено.
        try:
            # Выполняем HEAD с тайм-аутом, чтобы получить только статус и заголовки ответа.
            with opener.open(request, timeout=10):
                # Ответ без перенаправления означает, что новый адрес не нужен.
                break
        # urllib сообщает перенаправления как HTTPError благодаря защитному обработчику выше.
        except HTTPError as exc:
            # Принимаем только известные коды перехода и только если сервер указал следующий адрес.
            if exc.code not in (301, 302, 303, 307, 308) or not exc.headers.get("Location"):
                # Без стандартного статуса и заголовка Location безопасный переход невозможен.
                raise ValueError("Не удалось раскрыть короткую ссылку Google Maps.") from exc
            # Превращаем заголовок Location в полный адрес и проверим его на следующем шаге цикла.
            current = urljoin(current, exc.headers["Location"])
    # После остановки или исчерпания четырёх переходов пробуем извлечь координаты из последнего URL.
    return parse_google_maps_url(current)
