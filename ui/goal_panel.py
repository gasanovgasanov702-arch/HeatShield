"""Отдельная плашка цели: желаемая доля участка под будущими кронами."""

# Qt содержит обозначение горизонтальной ориентации для ползунка.
from PySide6.QtCore import Qt
# Эти виджеты нужны для поля процента, ползунка, шкалы выполнения и компоновки.
from PySide6.QtWidgets import QDoubleSpinBox, QFormLayout, QGroupBox, QLabel, QProgressBar, QSlider, QVBoxLayout


# Наследуем QGroupBox, чтобы вся цель выглядела одной подписанной плашкой.
class GoalPanel(QGroupBox):
    # Конструктор вызывается один раз при создании левой панели приложения.
    def __init__(self,parent=None)->None:
        # Передаём родительскому QGroupBox название плашки и родительский виджет.
        super().__init__("Желаемое улучшение",parent)
        # Вертикальная раскладка располагает поле, ползунок и текст друг под другом.
        layout=QVBoxLayout(self)
        # Форму используем для подписи слева от числового поля.
        form=QFormLayout()
        # QDoubleSpinBox позволяет вводить дробные проценты, например 0,25%.
        self.target=QDoubleSpinBox()
        # Цель не может быть отрицательной или превышать всю площадь участка.
        self.target.setRange(0,100)
        # Показываем два знака после запятой, чтобы маленькие доли были различимы.
        self.target.setDecimals(2)
        # Стрелки поля меняют цель на 0,05 процентного пункта за нажатие.
        self.target.setSingleStep(.05)
        # Видимый знак процента помогает не принять ввод за квадратные метры.
        self.target.setSuffix(" %")
        # Подсказка уточняет: речь о площади условной кроны, а не о температуре.
        self.target.setToolTip("Желаемая доля площади выбранного участка под новой условной кроной")
        # Добавляем поле и человекочитаемую подпись в форму.
        form.addRow("Новая тень на участке",self.target)
        # Вставляем заполненную форму в основную вертикальную раскладку.
        layout.addLayout(form)
        # Ползунок удобен для грубой настройки цели мышью без набора числа.
        self.slider=QSlider(Qt.Orientation.Horizontal)
        # Целые 0..10000 здесь соответствуют дробным 0,00..100,00%.
        self.slider.setRange(0,10000)
        # Шаг 5 на ползунке означает изменение цели на 0,05 процентного пункта.
        self.slider.setSingleStep(5)
        # При сдвиге ползунка переводим его целое значение в проценты делением на 100.
        self.slider.valueChanged.connect(lambda value:self.target.setValue(value/100))
        # При вводе числа перемещаем ползунок к соответствующему положению.
        self.target.valueChanged.connect(lambda value:self.slider.setValue(round(value*100)))
        # Показываем ползунок под числовым полем.
        layout.addWidget(self.slider)
        # Этот текст предотвращает ложное понимание цели как обещанного охлаждения воздуха.
        self.explanation=QLabel("0% — использовать весь лимит деревьев. Процент = объединённая площадь условных крон внутри участка / площадь участка. Это не снижение температуры.")
        # Разрешаем надписи переноситься, чтобы она помещалась в узкой боковой панели.
        self.explanation.setWordWrap(True)
        # Помещаем пояснение прямо рядом с настройкой, к которой оно относится.
        layout.addWidget(self.explanation)
        # Шкала ниже визуально показывает, удалось ли достичь заданной цели.
        self.progress=QProgressBar()
        # Шкала всегда показывает от 0 до 100 процентов выполнения цели.
        self.progress.setRange(0,100)
        # До анализа нет результата, поэтому значение равно нулю.
        self.progress.setValue(0)
        # При нулевой цели сообщаем, что шкалу пока не с чем сравнивать.
        self.progress.setFormat("Цель не задана")
        # Добавляем шкалу выполнения в плашку.
        layout.addWidget(self.progress)
        # Здесь позднее появится точное числовое объяснение достигнутой доли.
        self.status=QLabel("Цель ещё не рассчитана.")
        # Длинный результат тоже переносится по ширине боковой панели.
        self.status.setWordWrap(True)
        # Добавляем итоговый текст в нижнюю часть плашки.
        layout.addWidget(self.status)

    # При загрузке сценария задаём ранее сохранённую цель сразу в поле и ползунок.
    def set_target(self,value:float)->None:
        # Блокируем сигналы поля, чтобы программная установка не запустила лишний пересчёт.
        self.target.blockSignals(True)
        # Блокируем ответный сигнал ползунка по той же причине.
        self.slider.blockSignals(True)
        # Записываем сохранённое число процентов в поле.
        self.target.setValue(value)
        # Переводим проценты в целочисленную шкалу 0..10000.
        self.slider.setValue(round(value*100))
        # Возвращаем обычную реакцию поля на дальнейший ручной ввод.
        self.target.blockSignals(False)
        # Возвращаем обычную реакцию ползунка на дальнейшее перетаскивание.
        self.slider.blockSignals(False)

    # Обновляем надписи после анализа или изменения плана посадки.
    def show_metrics(self,metrics:dict)->None:
        # Если старый сценарий не содержит цель, берём пустой словарь без ошибки.
        goal=metrics.get("goal",{})
        # target — запрошенная пользователем доля участка в процентах.
        target=float(goal.get("target_percent",0))
        # actual — доля, которую действительно закрывают объединённые условные кроны.
        actual=float(goal.get("actual_percent",0))
        # Ноль означает, что Greedy должен использовать доступный лимит деревьев, а не останавливаться рано.
        if target<=0:
            # Не показываем ложный процент выполнения для отключённой цели.
            self.progress.setValue(0)
            # Подпись шкалы честно сообщает, что цель не задана.
            self.progress.setFormat("Цель не задана")
            # Убираем цвет прошлой успешной или неуспешной цели.
            self.status.setStyleSheet("")
            # Даже без цели показываем фактическую долю новой условной тени.
            self.status.setText(f"Цель отключена. Новая тень в текущем плане: {actual:.2f}% площади участка.")
            # Выходим: делить на нулевой target ниже нельзя.
            return
        # Отношение actual/target переводим в проценты выполнения и ограничиваем шкалу числом 100.
        self.progress.setValue(min(100,round(100*actual/target)))
        # %p — специальная подстановка Qt для текущего процента шкалы.
        self.progress.setFormat("Выполнение цели: %p%")
        # Проверяем сохранённый алгоритмом флаг достижения цели.
        if goal.get("reached"):
            # При успехе показываем фактическую и запрошенную доли рядом.
            self.status.setText(f"Цель по площади тени достигнута: {actual:.2f}% при запросе {target:.2f}%.")
            # Зелёный цвет помогает быстро заметить достижение цели.
            self.status.setStyleSheet("color:#176b4d;font-weight:600")
        # Если ограничений хватило только на меньшую долю, показываем нехватку.
        else:
            # max(0, ...) страхует от отрицательной нехватки из-за округления.
            self.status.setText(f"Текущий план дал {actual:.2f}% из {target:.2f}%. Не хватает {max(0,target-actual):.2f} п.п. при этих ограничениях и приоритетах.")
            # Янтарный цвет означает недостигнутую цель, а не программную ошибку.
            self.status.setStyleSheet("color:#a35a13;font-weight:600")
