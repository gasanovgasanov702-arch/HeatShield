"""Таблица сравнения двух планов, чтобы числовой результат был легко проверить."""

# Qt даёт сетку из строк и столбцов, подписанную группу и текстовые надписи.
from PySide6.QtWidgets import QGridLayout, QGroupBox, QLabel, QVBoxLayout


# Панель наследует QGroupBox, поэтому вокруг таблицы будет рамка с заголовком.
class ResultsPanel(QGroupBox):
    # Каждая пара хранит внутренний ключ показателя и понятное имя строки в интерфейсе.
    ROWS = (
        # Первые показатели отвечают на практические вопросы: сколько деревьев и сколько денег.
        ("trees", "Деревья"), ("cost", "Стоимость"), ("shade", "Новая тень"),
        # Доля участка, условный индекс жары и тень на путях описывают разные эффекты плана.
        ("share", "Доля участка"), ("heat", "Индекс жары"), ("routes", "Тень на путях"),
        # Последняя пара позволяет сравнить функцию оценки и скорость алгоритмов.
        ("utility", "Условная польза"), ("seconds", "Время"),
    )

    # Конструктор собирает пустую таблицу до первого анализа территории.
    def __init__(self, parent=None) -> None:
        # Создаём стандартную рамку Qt с названием результата.
        super().__init__("Результат анализа", parent)
        # Главная вертикальная раскладка содержит заголовок, таблицу и оговорку.
        layout = QVBoxLayout(self)
        # Пока данных нет, вместо чисел выводим инструкцию запустить анализ.
        self.label = QLabel("Запустите анализ территории.")
        # Имя позволяет отдельно стилизовать важный верхний блок в main.py.
        self.label.setObjectName("resultHeadline")
        # При узкой боковой панели длинная фраза переносится на новую строку.
        self.label.setWordWrap(True)
        # Размещаем заголовок выше таблицы.
        layout.addWidget(self.label)
        # Сетка даёт три столбца: название показателя, наш план и Random.
        grid = QGridLayout()
        # Небольшой горизонтальный отступ разделяет числа соседних столбцов.
        grid.setHorizontalSpacing(9)
        # Вертикальный отступ делает отдельные показатели различимыми.
        grid.setVerticalSpacing(7)
        # Нулевая строка сетки подписывает её первый столбец.
        grid.addWidget(QLabel("Показатель"), 0, 0)
        # Название среднего столбца меняется на «Ручной план» после правки дерева.
        self.plan_header = QLabel("План")
        # Ставим подпись среднего столбца в первую строку.
        grid.addWidget(self.plan_header, 0, 1)
        # Правый столбец всегда показывает воспроизводимый случайный план Random.
        grid.addWidget(QLabel("Random"), 0, 2)
        # Словарь позволит позже найти надписи нужной строки по ключу показателя.
        self.values: dict[str, tuple[QLabel, QLabel]] = {}
        # enumerate(..., 1) начинает строки данных после строки заголовков.
        for row, (key, name) in enumerate(self.ROWS, 1):
            # Понятное имя показателя будет слева от двух сравниваемых значений.
            title = QLabel(name)
            # Пока расчёта нет, среднее значение представляем прочерком.
            left = QLabel("—")
            # Такое же пустое значение показываем для Random.
            right = QLabel("—")
            # Отдельный стиль сделает числа заметнее названия строки.
            left.setObjectName("metricValue")
            # Для честного сравнения оба столбца оформлены одинаково.
            right.setObjectName("metricValue")
            # В текущую строку записываем название показателя.
            grid.addWidget(title, row, 0)
            # Значение выбранного или ручного плана стоит посередине.
            grid.addWidget(left, row, 1)
            # Значение случайного плана стоит справа.
            grid.addWidget(right, row, 2)
            # Запоминаем пару надписей, чтобы обновлять их после каждого пересчёта.
            self.values[key] = (left, right)
        # Добавляем готовую сетку под крупным итогом.
        layout.addLayout(grid)
        # Здесь ниже будет поясняться процент преимущества условной функции пользы.
        self.comparison = QLabel("Сравнение появится после анализа.")
        # Имя связывает блок с отдельным стилем из main.py.
        self.comparison.setObjectName("comparisonNote")
        # Позволяем объяснению занимать несколько строк, если места мало.
        self.comparison.setWordWrap(True)
        # Добавляем объяснение после числовых строк.
        layout.addWidget(self.comparison)
        # Предупреждаем, что модельные индексы не равны измеренной температуре и потоку людей.
        note = QLabel("Индекс и польза — расчётные оценки, не температура воздуха и не число прохожих.")
        # Делаем предупреждение читаемым на разных размерах окна.
        note.setWordWrap(True)
        # Цвет и шрифт делают его пояснением, а не главным результатом.
        note.setStyleSheet("color:#64786d;font-size:9pt")
        # Ставим предупреждение в конец панели.
        layout.addWidget(note)

    # При смене территории старые цифры надо убрать, чтобы не принять их за новый расчёт.
    def reset(self) -> None:
        # Возвращаем вместо итога приглашение запустить анализ.
        self.label.setText("Запустите анализ выбранного участка.")
        # Возвращаем нейтральное имя столбца, пока тип плана неизвестен.
        self.plan_header.setText("План")
        # Перебираем все пары чисел таблицы.
        for pair in self.values.values():
            # В каждой паре отдельно очищаем значение нашего плана и Random.
            for value in pair:
                # Прочерк не выглядит как реальный ноль или измеренное значение.
                value.setText("—")
        # Удаляем прежний процент сравнения вместе со старыми числами.
        self.comparison.setText("Сравнение появится после анализа.")

    # Функция вызывается после Greedy, ручного переноса или повторной оптимизации.
    def show_metrics(self, metrics: dict) -> None:
        # В compare() оба метода получают показатели в одинаковых единицах.
        plan, random = metrics["greedy"], metrics["random"]
        # После ручной правки не называем результат «Greedy»: это уже выбор пользователя.
        method = "Ручной план" if metrics.get("plan_method") == "manual" else "Greedy"
        # Главный итог показывает число деревьев и геометрическую долю новой кроны в участке.
        self.label.setText(f"{method}: {plan['trees']} деревьев · {plan['study_area_shaded_percent']:.3f}% участка под новой условной кроной")
        # Обновляем заголовок среднего столбца в соответствии с текущим способом выбора.
        self.plan_header.setText(method)
        # Для каждого ключа определяем, как переводить хранимое число в короткий видимый текст.
        for key, getter in (
            # Число деревьев — целое; деньги и квадратные метры разделяем пробелами для чтения.
            ("trees", lambda x: str(x["trees"])),
            # Цена берётся из расчёта плана, округляется до целых тенге и получает знак ₸.
            ("cost", lambda x: f"{x['cost']:,.0f} ₸".replace(",", " ")),
            # Площадь объединённых крон показываем в квадратных метрах без дробной части.
            ("shade", lambda x: f"{x['shade_m2']:,.0f} м²".replace(",", " ")),
            # Долю общей площади участка показываем с точностью до 0,001 процентного пункта.
            ("share", lambda x: f"{x['study_area_shaded_percent']:.3f}%"),
            # До и после здесь безразмерный индекс, а стрелка показывает направление изменения.
            ("heat", lambda x: f"{x['heat_index_before']:.4f} → {x['heat_index_after']:.4f}"),
            # Эта доля относится только к пешеходным путям, известным OpenStreetMap.
            ("routes", lambda x: f"{x['mapped_walk_network_shaded_percent']:.3f}%"),
            # Условная польза нужна для сравнения алгоритмов, а секунды — для скорости.
            ("utility", lambda x: f"{x['relative_utility']:.2f}"),
            # Время алгоритма измерено в секундах и показано с двумя знаками после запятой.
            ("seconds", lambda x: f"{x['seconds']:.2f} с"),
        ):
            # Получаем две надписи нужной строки из словаря, созданного конструктором.
            left, right = self.values[key]
            # Одной и той же функцией форматируем результат выбранного плана.
            left.setText(getter(plan))
            # Той же функцией форматируем Random, чтобы точность не отличалась.
            right.setText(getter(random))
        # compare() может не дать процент, если сравнение математически некорректно.
        gain = metrics.get("improvement_percent")
        # Например, при разных числах деревьев или нулевой пользе Random процент не определён.
        if gain is None:
            # Уточняем пользователю, почему именно нет числового процента.
            reason = "разное число деревьев" if not metrics.get("comparable", True) else "нулевая база Random"
            # Показываем причину вместо вымышленного процента.
            self.comparison.setText(f"Разница условной пользы не рассчитывается: {reason}.")
        # Если оба метода сопоставимы, выводим найденное значение.
        else:
            # Предупреждаем, что выигрыш по пользе не обязан означать выигрыш по каждой метрике.
            self.comparison.setText(f"Условная польза {method} относительно Random: {gain:+.1f}%. Смотрите также тень и индекс жары: они могут меняться иначе.")
