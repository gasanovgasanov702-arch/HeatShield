"""Visible quality checks and data-coverage warnings."""
# Панель показывает пользователю результаты аудита геометрии и ограничения данных карты.

# Группа даёт заголовок, метки показывают текст, а вертикальная форма располагает их столбцом.
from PySide6.QtWidgets import QGroupBox, QLabel, QVBoxLayout

# Эти настройки объясняют пользователю допущения модели тени.
from config import CANOPY_RADIUS_M, SHADE_INDEX_RESPONSE


# Группа показывает, прошли ли рекомендации геометрическую проверку и какие есть предупреждения.
class AuditPanel(QGroupBox):
    # parent позволяет разместить панель внутри основного окна Qt.
    def __init__(self,parent=None)->None:
        # Показываем видимый заголовок над результатами проверки.
        super().__init__("Проверка рекомендаций",parent)
        # Создаём вертикальный контейнер для статуса и пояснения модели.
        layout=QVBoxLayout(self)
        # До анализа сообщаем, что проверка ещё не запускалась.
        self.label=QLabel("Проверка появится после анализа OSM.")
        # Разрешаем перенос текста, чтобы длинные сообщения помещались в узкой панели.
        self.label.setWordWrap(True)
        # Включаем основную метку в вертикальную компоновку.
        layout.addWidget(self.label)
        # Объясняем радиус условной кроны и сценарный коэффициент, а также пределы этих допущений.
        assumptions=QLabel(f"Допущения: крона {CANOPY_RADIUS_M:g} м; сценарный отклик индекса под ней до {100*SHADE_INDEX_RESPONSE:g}%. Коэффициент не обучен на измерениях. Вода проверяется как препятствие, без универсального эффекта охлаждения.")
        # Длинное пояснение тоже переносится по ширине панели.
        assumptions.setWordWrap(True)
        # Делаем поясняющий текст приглушённым и немного меньшим, чем основной статус.
        assumptions.setStyleSheet("color:#66766c;font-size:9pt")
        # Добавляем блок допущений под результатом проверки.
        layout.addWidget(assumptions)

    # Превращает записи аудита из метрик в понятный статус и предупреждения на экране.
    def show_audit(self,metrics:dict)->None:
        # Берём вложенные данные аудита; если их нет, считаем, что сценарий не был независимо проверен.
        audit=metrics.get("audit",{})
        # Отдельно сообщаем, что старый сохранённый сценарий не содержит свежего аудита.
        if not audit:
            # Без сохранённых результатов проверки нельзя утверждать, что точки уже сверены с OSM.
            self.label.setText("Сохранённый сценарий без независимой проверки геометрии. Выполните новый анализ для проверки.")
            # Завершаем обновление, чтобы не показывать пустой или устаревший статус ниже.
            return
        # Получаем перечень найденных нарушений геометрических ограничений.
        violations=audit.get("violations",[])
        # Если нарушения есть, показываем не больше первых трёх, чтобы текст оставался компактным.
        if violations:
            # Объединяем первые сообщения в одну строку для главного статуса панели.
            status="Найдены нарушения: "+"; ".join(violations[:3])
        # При отсутствии нарушений показываем объём проверки и число проверенных деревьев.
        else:
            # Читаем числа из аудита с нулём по умолчанию, если конкретное поле отсутствует.
            status=(f"При анализе проверено {audit.get('checked',0)} кандидатов по геометрии OSM и добавленных GeoJSON; "
                    # Вторая часть сообщает число проверенных деревьев и итог столкновений в плане.
                    f"в текущем плане {audit.get('selected_checked',0)} деревьев, пересечений с известными препятствиями нет.")
        # Копируем предупреждения из аудита, чтобы безопасно добавлять к ним UI-пояснения.
        warnings=list(audit.get("warnings",[]))
        # Если планы сопоставимы и случайный план лучше, предупреждаем о возможном влиянии весов.
        if metrics.get("comparable") and metrics["greedy"]["relative_utility"]<metrics["random"]["relative_utility"]:
            # Пользовательское сообщение поясняет, что контрольный случайный план может выигрывать по выбранным весам.
            warnings.append("Random оказался лучше по условной функции пользы: проверьте веса и сценарий.")
        # Обновляем надпись статусом и, если они есть, предупреждениями на отдельных строках.
        self.label.setText(status+("\n"+"\n".join(warnings) if warnings else ""))
