import math
# pytest.raises позволяет проверить, что некорректные настройки приводят именно к ожидаемой ошибке.
import pytest

# Candidate — одно разрешённое место для дерева: здесь x задан в метрах на плоскости,
# а i задаёт номер места. Значения баллов ниже специально различаются между местами.
from core.free_space import Candidate
# Settings задаёт ограничения; функции ниже строят план и проверяют ручной выбор/перемещение.
from core.optimizer import Settings, evaluate_selection, greedy, random_placement
# move_tree отдельно проверяет перенос на ближайший кандидат с повторным соблюдением ограничений.
from core.optimizer import move_tree
# box задаёт полигон области, нужный для вычисления процента затенения.
from shapely.geometry import box


# Создаёт одинаковый небольшой набор кандидатов, используемый несколькими проверками оптимизатора.
def candidates():
    # Создаём 6 тестовых мест через каждые 8 м по оси x; нулевые координаты y/широты/долготы
    # упрощают геометрию, а три последних числа задают меняющиеся оценки мест.
    return [Candidate(i,i*8.0,0,0,0,1.0-i*.1,.3+i*.1,.5) for i in range(6)]


# Проверяет ограничения бюджета и расстояния, отсутствие дублей и повторяемость случайного алгоритма.
def test_budget_distance_seed_and_no_duplicates():
    # Просим посадить до 5 деревьев, но бюджет 30 при цене 10 за дерево разрешает максимум 3;
    # минимальная дистанция 12 м и seed=7 проверяют разнесение и повторяемость случайного выбора.
    settings=Settings(trees=5,budget=30,cost_per_tree=10,minimum_distance_m=12,seed=7)
    # Сравниваем жадный и случайный алгоритмы на одинаковых местах и ограничениях.
    for result in (greedy(candidates(),settings),random_placement(candidates(),settings)):
        # Бюджета хватит не более чем на 3 дерева, даже если запрошено 5.
        assert len(result.ids)<=3
        # Каждый номер выбранного места должен быть уникальным: нельзя посадить дважды в одну точку.
        assert len(result.ids)==len(set(result.ids))
        # Координата места i равна i*8 м; разница индексов, умноженная на 8, даёт расстояние в метрах.
        # Каждая пара деревьев обязана быть разделена как минимум 12 м.
        assert all(abs(a-b)*8>=12 for i,a in enumerate(result.ids) for b in result.ids[i+1:])
        # Площадь тени измеряется в м² и не может быть отрицательной.
        assert result.shaded_area_m2>=0
    # Один seed должен приводить к одному и тому же случайному плану при повторном запуске.
    assert random_placement(candidates(),settings).ids==random_placement(candidates(),settings).ids


# Проверяет, что ручной список id отклоняется при нарушении дистанции или лимита деревьев.
def test_manual_selection_enforces_limits():
    # Настройки разрешают максимум 2 дерева, бюджет 20 (2 × 10), расстояние между ними — 12 м.
    settings=Settings(trees=2,budget=20,cost_per_tree=10,minimum_distance_m=12)
    # Места 0 и 1 удалены лишь на 8 м, поэтому ручной план должен быть отклонён.
    with pytest.raises(ValueError):evaluate_selection(candidates(),[0,1],settings)
    # Три выбранных места превышают лимит в 2 дерева, даже если их расстояния подходят.
    with pytest.raises(ValueError):evaluate_selection(candidates(),[0,2,4],settings)
    # Места 0 и 2 отстоят на 16 м, укладываются в лимит и должны сохраниться в плане.
    assert evaluate_selection(candidates(),[0,2],settings).ids==[0,2]


# Отрицательный бюджет не имеет смысла, поэтому оптимизатор должен отказать с ValueError.
def test_negative_budget_rejected():
    # Отрицательный бюджет (-1 денежная единица) невозможен, поэтому оптимизатор должен сообщить ValueError.
    with pytest.raises(ValueError):greedy(candidates(),Settings(budget=-1))


# Проверяет остановку жадного алгоритма сразу после достижения процента затенения, если цель достижима.
def test_shade_target_stops_at_smallest_greedy_prefix():
    # Четыре места расположены внутри квадрата; координаты x идут от 20 до 80 м с шагом 20 м.
    # Долготы слегка различаются, а три оценки каждого места равны 0.6.
    items=[Candidate(i,20+i*20,20,0,i*.0002,.6,.6,.6) for i in range(4)]
    # Квадрат 100 на 100 м имеет площадь 10 000 м²; он задаёт знаменатель для процента затенения.
    region=box(0,0,100,100)
    # Цель 1% должна достигаться одним деревом, если его тени достаточно; максимум всё равно 4 дерева.
    one=greedy(items,Settings(trees=4,budget=40000,target_shade_percent=1),region)
    # Цель 20% выше достижимого этой небольшой тестовой выборкой, поэтому проверяется полный план.
    impossible=greedy(items,Settings(trees=4,budget=40000,target_shade_percent=20),region)
    # Проверяем, что при достижимой цели алгоритм останавливается на минимальном префиксе из одного дерева.
    assert len(one.ids)==1
    # Для недостижимой цели алгоритм использует все четыре доступных места, а не останавливается рано.
    assert len(impossible.ids)==4
    # shaded_area_m2 / region.area переводит площадь тени в долю; умножение на 100 — в проценты.
    assert 100*one.shaded_area_m2/region.area>=1


# Проверяет привязку перетаскивания к кандидатам и отказ при нарушении расстояния или выборе вне сетки.
def test_move_snaps_to_candidate_and_rechecks_spacing():
    # Три места лежат на оси x через 30 м; изменение долготы на 0.0002695° примерно соответствует 30 м.
    items=[Candidate(i,i*30,0,0,i*.0002695,.5,.5,.5) for i in range(3)]
    # Можно выбрать 2 дерева, на каждое выделено 10 000, а минимальный интервал равен 20 м.
    settings=Settings(trees=2,budget=20000,cost_per_tree=10000,minimum_distance_m=20)
    # Переносим выбранное дерево с места 0 в запрошенные координаты около места 1.
    # Функция должна привязать запрос к существующему месту и вернуть новый план, id и расстояние (метры).
    moved,new_id,distance=move_tree(items,[0],0,0,items[1].lon,settings)
    # Итоговый план содержит место 1, его id равен 1, а привязка должна быть ближе одного метра.
    assert moved.ids==[1] and new_id==1 and distance<1
    # При интервале 40 м место 1 слишком близко к уже занятому месту 2 (30 м), значит перенос запрещён.
    with pytest.raises(ValueError):move_tree(items,[0,2],0,0,items[1].lon,
                                            # Здесь поднимаем минимальную дистанцию до 40 м; бюджет по-прежнему разрешает оба дерева.
                                            Settings(trees=2,budget=20000,cost_per_tree=10000,minimum_distance_m=40))
    # Долгота 1° далеко за пределами тестовых мест; нельзя переместить дерево в точку без кандидата.
    with pytest.raises(ValueError):move_tree(items,[0],0,0,1,settings)
