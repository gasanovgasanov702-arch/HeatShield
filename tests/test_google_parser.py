# pytest параметризует входные ссылки и проверяет ожидаемое ValueError для недопустимых адресов.
import pytest

# parse_google_maps_url извлекает широту и долготу из поддерживаемых ссылок Google Maps.
from core.google_parser import parse_google_maps_url


# pytest подставит каждую пару URL и координат в один тест.
@pytest.mark.parametrize("url, expected", [
    # Координаты после @ идут в порядке широта 43.2389°, долгота 76.8897°; масштаб карты — 15z.
    ("https://www.google.com/maps/@43.2389,76.8897,15z", (43.2389, 76.8897)),
    # Параметр q содержит координаты 43.2° с.ш. и 76.8° в.д.
    ("https://www.google.com/maps?q=43.2,76.8", (43.2, 76.8)),
    # Короткая форма ll поддерживается для домена maps.google.com, включая отрицательную широту.
    ("https://maps.google.com/?ll=-12.5,34.25", (-12.5, 34.25)),
# Закрываем список тестовых пар; каждая пара выше превращается в отдельный запуск test_known_urls.
])
# Имя функции подчёркивает проверку поддерживаемых форматов Google Maps URL.
def test_known_urls(url, expected):
    # Парсер должен вернуть числовую пару координат точно в ожидаемом порядке (широта, долгота).
    assert parse_google_maps_url(url) == expected


# Здесь переданы заведомо неподдерживаемые или опасные ссылки: неправильный домен/схема/формат/диапазон.
@pytest.mark.parametrize("url", [
    # Поддельный домен не является Google, а file:// пытается открыть локальный файл вместо карты.
    "https://evil.example/maps/@43,76", "file:///etc/passwd", "https://www.google.com.evil.example/maps/@43,76",
    # Короткие ссылки app.goo.gl не содержат координат для этого парсера; широта 99° и долгота 200° вне диапазона.
    "https://maps.app.goo.gl/abcd", "https://www.google.com/maps/@99,200,15z",
# Закрываем список URL, которые не должны приниматься парсером.
])
# Имя функции подчёркивает проверку отказа для неверных или небезопасных ссылок.
def test_invalid_urls(url):
    # Для каждой плохой ссылки ожидаем ValueError вместо принятия чужого домена или невозможных координат.
    with pytest.raises(ValueError):
        # Именно эту ссылку из параметров теста пытаемся разобрать.
        parse_google_maps_url(url)
