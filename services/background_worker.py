"""Фоновая Qt-задача, чтобы запросы OSM и георасчёты не блокировали окно."""

# Аннотации типов отложены, чтобы их имена не требовали вычисления при импорте модуля.
from __future__ import annotations

# traceback печатает полную причину сбоя в консоль разработчика, а Callable описывает переданную функцию.
import traceback
# Callable нужен подсказке типов: Worker принимает любую вызываемую функцию анализа.
from collections.abc import Callable

# QObject и QRunnable интегрируют задачу с потоками Qt; Signal передаёт результат/ошибку в интерфейс.
from PySide6.QtCore import QObject, QRunnable, Signal, Slot


# Объявляет два сигнала, через которые рабочий поток сообщает интерфейсу результат или ошибку.
class WorkerSignals(QObject):
    # finished передаёт результат функции как Python-объект обратно в GUI-поток через механизм сигналов Qt.
    finished = Signal(object)
    # failed передаёт короткий текст ошибки, чтобы интерфейс мог показать пользователю понятное сообщение.
    failed = Signal(str)


# Обёртка над функцией, которую QThreadPool запускает вне GUI-потока.
class Worker(QRunnable):
    # Сохраняет функцию и её параметры; run вызовет функцию позже в рабочем потоке.
    def __init__(self, function: Callable, *args, **kwargs) -> None:
        # Инициализируем QRunnable, чтобы QThreadPool мог запускать объект как фоновую работу.
        super().__init__()
        # Сохраняем анализатор/экспорт-функцию, не вызывая её пока — вызов будет в run().
        self.function = function
        # Позиционные аргументы сохраняются отдельно и передаются функции при старте фоновой задачи.
        self.args = args
        # Именованные параметры (например, настройки анализа) тоже нужно сохранить для будущего вызова.
        self.kwargs = kwargs
        # Создаём сигналы заранее, чтобы GUI мог подключиться к ним до запуска потока.
        self.signals = WorkerSignals()

    # Декоратор отмечает метод как слот Qt: его можно безопасно вызывать через механизм Qt.
    @Slot()
    # Slot сообщает Qt, что run — метод-приёмник, который можно безопасно запускать через механизм сигналов/потоков.
    # Выполняет задачу и отправляет итог сигналом, чтобы основной поток интерфейса оставался отзывчивым.
    def run(self) -> None:
        # Qt вызывает run() в рабочем потоке, поэтому долгие запросы к OSM и георасчёты не замораживают окно.
        try:
            # Выполняем переданную функцию с сохранёнными аргументами и отправляем результат подписчикам GUI.
            self.signals.finished.emit(self.function(*self.args, **self.kwargs))
        # Ловим обычные исключения, чтобы задача не завершилась молча и приложение могло сообщить об ошибке.
        except Exception as exc:
            # Полный traceback помогает разработчику найти строку сбоя в журнале запуска.
            traceback.print_exc()
            # В сигнал интерфейса передаём текст ошибки; GUI может показать его, не получая сам объект исключения.
            self.signals.failed.emit(str(exc))
